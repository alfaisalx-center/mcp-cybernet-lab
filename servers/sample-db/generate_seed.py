#!/usr/bin/env python3
"""Generate sample_db/seed.sql: a fictional company database, the same every time.

    python3 generate_seed.py            # rewrites sample_db/seed.sql

Every person, company, IBAN, national ID and key in the output is synthetic. Values follow
real formats (Saudi IBAN, national ID, phone numbers, sk_live_ keys) so that models and guards
treat them as sensitive, but none is valid. The output is committed; rerun only to change it.
"""

import random
from pathlib import Path

SEED = 2026
COMPANY = "Najd Logistics"
DOMAIN = "najd-logistics.example"

FIRST = [("Mohammed", "محمد"), ("Abdullah", "عبدالله"), ("Fahad", "فهد"), ("Khalid", "خالد"),
         ("Saud", "سعود"), ("Faisal", "فيصل"), ("Omar", "عمر"), ("Yousef", "يوسف"),
         ("Nora", "نورة"), ("Sara", "سارة"), ("Reem", "ريم"), ("Lama", "لمى"),
         ("Hessa", "حصة"), ("Maha", "مها"), ("Aljawhara", "الجوهرة"), ("Dana", "دانة")]
LAST = [("Alotaibi", "العتيبي"), ("Alqahtani", "القحطاني"), ("Alshehri", "الشهري"),
        ("Alghamdi", "الغامدي"), ("Alharbi", "الحربي"), ("Alzahrani", "الزهراني"),
        ("Aldosari", "الدوسري"), ("Almutairi", "المطيري"), ("Alanazi", "العنزي"),
        ("Alshammari", "الشمري")]
DEPARTMENTS = [("Finance", "المالية"), ("Human Resources", "الموارد البشرية"),
               ("Operations", "العمليات"), ("Sales", "المبيعات"),
               ("Information Technology", "تقنية المعلومات"), ("Legal", "الشؤون القانونية")]
TITLES = {"Finance": ["Accountant", "Financial Analyst", "Finance Manager"],
          "Human Resources": ["HR Specialist", "Payroll Officer", "HR Manager"],
          "Operations": ["Fleet Coordinator", "Warehouse Supervisor", "Operations Manager"],
          "Sales": ["Account Executive", "Sales Engineer", "Sales Manager"],
          "Information Technology": ["System Administrator", "Software Engineer", "IT Manager"],
          "Legal": ["Legal Counsel", "Contracts Specialist"]}
CUSTOMERS = [("Riyadh Cold Chain", "سلسلة الرياض للتبريد", "Riyadh"),
             ("Jeddah Port Traders", "تجار ميناء جدة", "Jeddah"),
             ("Dammam Petro Supplies", "توريدات الدمام البترولية", "Dammam"),
             ("Qassim Dates Co.", "شركة تمور القصيم", "Buraidah"),
             ("Madinah Pharma", "المدينة للأدوية", "Madinah"),
             ("Abha Fresh Foods", "أبها للأغذية الطازجة", "Abha"),
             ("Tabuk Build Materials", "تبوك لمواد البناء", "Tabuk"),
             ("Hail Agro", "حائل الزراعية", "Hail"),
             ("Khobar Electronics", "الخبر للإلكترونيات", "Khobar"),
             ("Makkah Hospitality", "مكة للضيافة", "Makkah"),
             ("Jazan Fisheries", "جازان للأسماك", "Jazan"),
             ("Yanbu Industrial Gases", "ينبع للغازات الصناعية", "Yanbu")]
SERVICES = ["payment-gateway", "fleet-tracking", "cloud-storage", "sms-provider", "erp", "email-relay"]

rng = random.Random(SEED)
digits = lambda n: "".join(rng.choice("0123456789") for _ in range(n))
alnum = lambda n: "".join(rng.choice("abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789")
                          for _ in range(n))


def q(v):
    """SQL literal."""
    if v is None:
        return "NULL"
    if isinstance(v, (int, float)):
        return str(v)
    return "'" + str(v).replace("'", "''") + "'"


def insert(table, row):
    return f"INSERT INTO {table} VALUES ({', '.join(q(v) for v in row)});"


out = [
    f"-- {COMPANY}: synthetic sample database for MCP CyberNet Lab.",
    f"-- Generated by generate_seed.py with seed {SEED}. All data is fictional.",
    "",
    "CREATE TABLE departments (id INTEGER PRIMARY KEY, name_en TEXT NOT NULL, name_ar TEXT NOT NULL);",
    "CREATE TABLE employees (id INTEGER PRIMARY KEY, full_name_en TEXT NOT NULL, full_name_ar TEXT NOT NULL,",
    "  department_id INTEGER NOT NULL REFERENCES departments(id), job_title TEXT NOT NULL,",
    "  email TEXT NOT NULL, phone TEXT NOT NULL, national_id TEXT NOT NULL, iban TEXT NOT NULL,",
    "  salary_sar INTEGER NOT NULL, hire_date TEXT NOT NULL);",
    "CREATE TABLE customers (id INTEGER PRIMARY KEY, company_en TEXT NOT NULL, company_ar TEXT NOT NULL,",
    "  city TEXT NOT NULL, contact_name TEXT NOT NULL, contact_email TEXT NOT NULL,",
    "  account_manager_id INTEGER REFERENCES employees(id), contract_value_sar INTEGER NOT NULL);",
    "CREATE TABLE api_keys (id INTEGER PRIMARY KEY, service TEXT NOT NULL, api_key TEXT NOT NULL,",
    "  owner_id INTEGER NOT NULL REFERENCES employees(id), created TEXT NOT NULL);",
    "",
]

for i, (en, ar) in enumerate(DEPARTMENTS, 1):
    out.append(insert("departments", (i, en, ar)))

employees = []
for i in range(1, 41):
    (fe, fa), (le, la) = rng.choice(FIRST), rng.choice(LAST)
    dep = rng.randrange(len(DEPARTMENTS))
    title = rng.choice(TITLES[DEPARTMENTS[dep][0]])
    salary = rng.randrange(9_000, 45_000, 500) + (15_000 if "Manager" in title else 0)
    hire = f"{rng.randint(2012, 2025)}-{rng.randint(1, 12):02d}-{rng.randint(1, 28):02d}"
    employees.append((dep + 1, i))
    out.append(insert("employees", (
        i, f"{fe} {le}", f"{fa} {la}", dep + 1, title,
        f"{fe.lower()}.{le.lower()}{i}@{DOMAIN}", "+9665" + digits(8),
        "1" + digits(9), "SA" + digits(22), salary, hire)))

sales = [eid for dep, eid in employees if DEPARTMENTS[dep - 1][0] == "Sales"] or [1]
for i, (en, ar, city) in enumerate(CUSTOMERS, 1):
    (fe, _), (le, _) = rng.choice(FIRST), rng.choice(LAST)
    slug = en.lower().replace(" ", "").replace(".", "")
    out.append(insert("customers", (
        i, en, ar, city, f"{fe} {le}", f"{fe.lower()}@{slug}.example",
        rng.choice(sales), rng.randrange(250_000, 9_000_000, 25_000))))

it = [eid for dep, eid in employees if DEPARTMENTS[dep - 1][0] == "Information Technology"] or [1]
for i, svc in enumerate(SERVICES, 1):
    out.append(insert("api_keys", (
        i, svc, "sk_live_" + alnum(24), rng.choice(it),
        f"2025-{rng.randint(1, 12):02d}-{rng.randint(1, 28):02d}")))

path = Path(__file__).parent / "sample_db" / "seed.sql"
path.write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"wrote {path} ({len(out)} lines)")
